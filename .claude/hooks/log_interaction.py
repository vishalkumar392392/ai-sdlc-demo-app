#!/usr/bin/env python3
"""Claude Code hook: append every AI interaction to ai-logs/ai-interactions.jsonl
in one fixed schema, and re-render ai-logs/AI_INTERACTIONS.md on Stop.

Schema (one JSON object per line, always these keys):
  ts, session, event, actor, tool, summary
"""
import json, os, re, sys, datetime

ROOT = os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
LOG_DIR = os.path.join(ROOT, "ai-logs")
JSONL = os.path.join(LOG_DIR, "ai-interactions.jsonl")
MARKDOWN = os.path.join(LOG_DIR, "AI_INTERACTIONS.md")
MAX = 400
SECRET = re.compile(r"(gh[opsu]_[A-Za-z0-9]{20,}|Bearer\s+[A-Za-z0-9._-]{16,}|[\w.+-]+@[\w-]+\.[\w.]+)")


def clean(text):
    text = SECRET.sub("[redacted]", str(text or ""))
    text = " ".join(text.split())
    return text if len(text) <= MAX else text[: MAX - 1] + "…"


def summarize_tool_input(tool, data):
    if not isinstance(data, dict):
        return clean(data)
    for key in ("description", "command", "file_path", "prompt", "pattern", "skill", "url"):
        if data.get(key):
            return clean(f"{key}={data[key]}")
    return clean(json.dumps(data)[:MAX])


def record(event):
    name = event.get("hook_event_name", "Unknown")
    tool = event.get("tool_name", "")
    actor = event.get("agent_type") or ("subagent" if event.get("agent_id") else "main-agent")
    if name == "UserPromptSubmit":
        actor, summary = "user", clean(event.get("prompt"))
    elif name == "PreToolUse":
        summary = summarize_tool_input(tool, event.get("tool_input"))
    elif name == "PostToolUse":
        response = event.get("tool_response")
        status = "error" if isinstance(response, dict) and response.get("is_error") else "ok"
        summary = f"{status}: {summarize_tool_input(tool, event.get('tool_input'))}"
    elif name == "SubagentStop":
        summary = clean(event.get("last_assistant_message") or "subagent finished")
    elif name == "Stop":
        summary = clean(event.get("last_assistant_message") or "turn finished")
    else:
        summary = clean(json.dumps({k: v for k, v in event.items() if k not in ("transcript_path", "cwd")})[:MAX])
    return {
        "ts": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "session": str(event.get("session_id", ""))[:8],
        "event": name,
        "actor": actor,
        "tool": tool,
        "summary": summary,
    }


def render_markdown():
    rows = []
    with open(JSONL, encoding="utf-8") as handle:
        for line in handle:
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    out = ["# AI interaction log", "",
           "Generated by `.claude/hooks/log_interaction.py` from `ai-interactions.jsonl`. Do not edit by hand.", "",
           "| Time (UTC) | Session | Event | Actor | Tool | Summary |",
           "| --- | --- | --- | --- | --- | --- |"]
    for row in rows:
        cells = [row.get(k, "") for k in ("ts", "session", "event", "actor", "tool", "summary")]
        out.append("| " + " | ".join(str(c).replace("|", "\\|") for c in cells) + " |")
    with open(MARKDOWN, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out) + "\n")


def main():
    try:
        event = json.load(sys.stdin)
    except json.JSONDecodeError:
        return 0
    os.makedirs(LOG_DIR, exist_ok=True)
    with open(JSONL, "a", encoding="utf-8") as handle:
        handle.write(json.dumps(record(event), ensure_ascii=False) + "\n")
    if event.get("hook_event_name") in ("Stop", "SubagentStop"):
        render_markdown()
    return 0


if __name__ == "__main__":
    sys.exit(main())
